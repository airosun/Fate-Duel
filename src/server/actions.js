// Socket event -> RoomManager call. Shared by the server (online rooms) and the browser,
// which runs its own RoomManager for a local Holy Grail War against six CPUs.
export const ACTIONS = {
  'room:role': (rm, room, id, { role }) => rm.setRole(room, id, role),
  'room:start': (rm, room, id) => rm.start(room, id),
  'select:focus': (rm, room, id, { servantId }) => rm.focus(room, id, servantId),
  'select:pick': (rm, room, id, { servantId }) => rm.pick(room, id, servantId),
  'battle:draft': (rm, room, id, { action }) => rm.draft(room, id, action),
  'battle:lock': (rm, room, id, { action }) => rm.lock(room, id, action),
  'battle:unlock': (rm, room, id) => rm.unlock(room, id),
  'battle:foresight': (rm, room, id) => rm.foresight(room, id),
  'battle:continue': (rm, room, id) => rm.continueTurn(room, id),
  'battle:divine': (rm, room, id, { use }) => rm.divineDecision(room, id, use),
  'match:rematch': (rm, room, id, { choice }) => rm.rematch(room, id, choice),
  'match:return': (rm, room, id) => rm.returnToRoom(room, id),
  'war:start': (rm, room, id) => rm.startWar(room, id),
  'war:draft': (rm, room, id, { cls }) => rm.warDraft(room, id, cls),
  'war:pick': (rm, room, id, { servantId }) => rm.warPick(room, id, servantId),
  'war:watch': (rm, room, id, { fightId }) => rm.warSpectate(room, id, fightId),
  'war:hub': (rm, room, id) => rm.warHub(room, id),
  'war:replay': (rm, room, id, { toEnd }) => rm.warReplayNext(room, id, { toEnd: !!toEnd }),
  'war:ready': (rm, room, id) => rm.warReady(room, id),
  'war:return': (rm, room, id) => rm.warReturn(room, id),
};
